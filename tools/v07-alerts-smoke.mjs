import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const src=fs.readFileSync(new URL('../desk-v07-alerts.js',import.meta.url),'utf8');
const SG={id:'sg',name:'Singapore',country:'Singapore',timezone:'Asia/Singapore',latitude:1.3521,longitude:103.8198};
const US={id:'hou',name:'Houston',country:'United States',timezone:'America/Chicago',latitude:29.76,longitude:-95.36};
const state={activePage:'overview',pages:[{id:'overview',modules:[{type:'weather',config:{cities:[SG,US]}}]}]};
const window={DeskV07:{},DeskBridge:{getState:()=>state,save:()=>{}},DeskAir:{indexType:c=>c.id==='sg'?'psi':'us_aqi',load:async()=>({kind:'psi',psi:{north:150}})}};
const handlers={};
let calls=0;
const document={addEventListener:(event,fn)=>handlers[event]=fn,querySelector:()=>null,visibilityState:'visible'};
const ctx={window,document,Date,URL,AbortSignal,Intl,Number,console,setInterval:()=>{},fetch:async url=>{
 calls++;assert.match(url,/api.open-meteo.com\/v1\/forecast/);return {ok:true,json:async()=>({current:{time:'2026-10-09T12:00',weather_code:1},hourly:{time:['2026-10-09T12:00','2026-10-09T13:00'],precipitation_probability:[45,82],weather_code:[1,95]}})};}};
