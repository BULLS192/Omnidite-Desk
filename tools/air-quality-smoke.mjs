import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const code=fs.readFileSync(new URL('../air-quality.js',import.meta.url),'utf8');
const requests=[], window={};
const psi={code:1,data:{items:[{timestamp:'2026-10-09T18:00:00+08:00',readings:{psi_twenty_four_hourly:{north:135,south:167,east:166,west:187,central:192}}}]}};
const pm={code:1,data:{items:[{timestamp:'2026-10-09T18:00:00+08:00',readings:{pm25_one_hourly:{north:80,south:68,east:114,west:110,central:123}}}]}};
const model={current:{time:'2026-10-09T10:00',us_aqi:151,european_aqi:75,pm2_5:45,pm10:90},hourly:{time:['2026-10-09T09:00','2026-10-09T10:00','2026-10-09T11:00'],us_aqi:[150,151,155],european_aqi:[60,75,80]}};
const fetch=async input=>{
 const url=String(input);requests.push(url);
 const body=url.endsWith('/psi')?psi:url.endsWith('/pm25')?pm:model;
 return {ok:true,json:async()=>body};
};
vm.runInNewContext(code,{window,fetch,URL,Date,Intl,AbortSignal,console});
const a=window.DeskAir;
assert.equal(a.indexType({name:'Singapore',country:'Singapore',timezone:'Asia/Singapore'}),'psi');
assert.equal(a.indexType({name:'Houston',country:'Texas, United States'}),'us_aqi');
assert.equal(a.indexType({name:'London',country:'England, United Kingdom'}),'european_aqi');
assert.equal(a.severity('psi',192).label,'Unhealthy');
assert.equal(a.severity('us_aqi',151).label,'Unhealthy');
assert.equal(a.severity('european_aqi',75).label,'Poor');
const sg={name:'Singapore',country:'Singapore',timezone:'Asia/Singapore',latitude:1.3521,longitude:103.8198};
const sgData=await a.load(sg);
assert.equal(sgData.psi.central,192);
assert.equal(sgData.pm25.central,123);
assert.match(a.detail(sgData,sg),/9 Oct 2026/);
assert.equal(sgData.pm25.central,123);
const sgCard=a.summary(sgData);
assert.match(sgCard,/PSI 192 · Unhealthy/);
assert.match(sgCard,/Highest region: Central/);
const sgDetail=a.detail(sgData,sg);
assert.match(sgDetail,/24-hour PSI/);
assert.match(sgDetail,/1-hour PM2.5/);
assert.match(sgDetail,/North/);
assert.match(sgDetail,/PM2.5 observed/);
await a.load(sg);
assert.equal(requests.length,2,'Singapore readings are cached by region, not fetched per widget');
const houston={name:'Houston',country:'Texas, United States',latitude:29.76,longitude:-95.37,timezone:'America/Chicago'};
const us=await a.load(houston);
assert.equal(us.kind,'us_aqi');
assert.match(a.summary(us),/US AQI 151/);
assert.match(a.detail(us,houston),/Model outlook/);
assert.match(requests.at(-1),/air-quality-api.open-meteo.com/);
const london={name:'London',country:'England, United Kingdom',latitude:51.50,longitude:-0.12,timezone:'Europe/London'};
const eu=await a.load(london);
assert.equal(eu.kind,'european_aqi');
assert.match(a.summary(eu),/European AQI 75 · Poor/);
assert.match(a.detail(eu,london),/not an official local station reading/);
const malicious={...london,name:'<script>alert(1)</script>',latitude:51.6};
const x=await a.load(malicious);
assert.doesNotMatch(a.detail(x,malicious),/<script>/);
assert.match(a.detail(x,malicious),/&lt;script&gt;/);
assert.equal(requests.length,5,'SG 2 endpoints + 3 geographic model locations');
console.log('PASS: NEA regional PSI/PM2.5, US/EU AQI, classification, cache, source labels, escaped city and model attribution');